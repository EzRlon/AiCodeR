package com.aicode.feature.settings.domain.feedback

import java.net.URLEncoder

/** 反馈类型：决定 Issue 标题前缀与仓库标签。 */
enum class FeedbackKind { SUGGESTION, BUG, OTHER }

/** 用户在反馈页填写的内容（诊断信息与日志由页面采集后填入）。 */
data class FeedbackDraft(
    val kind: FeedbackKind,
    val title: String,
    val description: String,
    val reproduction: String = "",
    val diagnostics: String = "",
    val logExcerpt: String = ""
)

/**
 * 一次反馈的产物：
 * - [fullBody] 完整正文，复制到剪贴板用（可超出链接长度上限）；
 * - [issueUrl] 可直接打开的 GitHub Issue 预填链接，正文可能被裁剪。
 */
data class FeedbackReport(
    val issueTitle: String,
    val fullBody: String,
    val issueUrl: String
)

/**
 * 把反馈内容拼成 GitHub Issue 正文与预填链接。
 *
 * 走「浏览器打开预填链接」而不是 App 内调 API：不需要后端、不需要在 App 里存 GitHub 令牌，
 * 用户用浏览器里已有的 GitHub 账号完成提交。代价是链接长度有限（中文 UTF-8 每字 3 字节、
 * 每字节编码成 `%XX` 3 字符，编码后约为原文的 9 倍），
 * 所以正文要先裁剪再进 URL，完整版由调用方复制到剪贴板兜底。
 */
object FeedbackReportBuilder {

    /** 反馈提交的目标仓库（与更新检查、关于页保持一致）。 */
    const val REPO_URL = "https://github.com/EzRlon/AiCodeR"

    /**
     * 专用 markdown 模板：GitHub 只会对 markdown 模板（而非 yml 表单）应用 `body` 预填，
     * 因此反馈功能单独用这个模板，不复用 bug_report.yml / feature_request.yml。
     */
    const val TEMPLATE_FILE = "in_app_feedback.md"

    /** 浏览器与 Intent 对超长 URL 的容忍度不一致，编码后留足余量。 */
    const val MAX_URL_CHARS = 7500

    private const val TRUNCATED_NOTICE =
        "> 说明：内容较长，链接中的正文已裁剪；完整内容请用 App 内「复制反馈内容」获取。"

    private const val TRUNCATED_NOTICE_EN =
        "> Note: the content is long, so the body in this link was truncated; use “Copy feedback” in the app for the full text."

    fun titlePrefix(kind: FeedbackKind, english: Boolean = false): String = when (kind) {
        FeedbackKind.SUGGESTION -> if (english) "[Suggestion]" else "[建议]"
        FeedbackKind.BUG -> "[Bug]"
        FeedbackKind.OTHER -> if (english) "[Feedback]" else "[反馈]"
    }

    /** 仓库里已有的标签；OTHER 不打标签，避免依赖不存在的标签。 */
    fun label(kind: FeedbackKind): String? = when (kind) {
        FeedbackKind.SUGGESTION -> "enhancement"
        FeedbackKind.BUG -> "bug"
        FeedbackKind.OTHER -> null
    }

    fun build(draft: FeedbackDraft, english: Boolean = false): FeedbackReport {
        val issueTitle = buildTitle(draft, english)
        val fullBody = composeBody(draft, english)
        val urlBody = fitForUrl(draft, issueTitle, fullBody, english)
        return FeedbackReport(
            issueTitle = issueTitle,
            fullBody = fullBody,
            issueUrl = buildUrl(issueTitle, urlBody, label(draft.kind))
        )
    }

    /** 标题为空时退回用描述首行，保证 Issue 不至于只有前缀。 */
    fun buildTitle(draft: FeedbackDraft, english: Boolean = false): String {
        val subject = draft.title.trim().ifBlank {
            draft.description.trim().lineSequence().firstOrNull().orEmpty().take(40).trim()
        }.ifBlank { if (english) "Untitled feedback" else "未命名反馈" }
        return "${titlePrefix(draft.kind, english)} $subject"
    }

    fun composeBody(draft: FeedbackDraft, english: Boolean = false): String = buildString {
        if (english) {
            appendLine("<!-- Generated by AiCodeR · Settings → Feedback. Please add any missing details before submitting. -->")
            appendLine()
            appendLine("## Type")
            appendLine(kindText(draft.kind, true))
            appendLine()
            appendLine("## Description")
            appendLine(draft.description.trim().ifBlank { "(not provided)" })
            if (draft.kind == FeedbackKind.BUG && draft.reproduction.isNotBlank()) {
                appendLine()
                appendLine("## Steps to reproduce")
                appendLine(draft.reproduction.trim())
            }
            if (draft.diagnostics.isNotBlank()) {
                appendLine()
                appendLine("## Environment")
                appendLine(draft.diagnostics.trim())
            }
            if (draft.logExcerpt.isNotBlank()) {
                appendLine()
                appendLine("## Log excerpt (redacted)")
                appendLine("```text")
                appendLine(draft.logExcerpt.trim())
                appendLine("```")
            }
        } else {
            appendLine("<!-- 由 AiCodeR「设置 → 反馈与建议」生成，请补充必要信息后再提交。 -->")
            appendLine()
            appendLine("## 反馈类型")
            appendLine(kindText(draft.kind))
            appendLine()
            appendLine("## 描述")
            appendLine(draft.description.trim().ifBlank { "（未填写）" })
            if (draft.kind == FeedbackKind.BUG && draft.reproduction.isNotBlank()) {
                appendLine()
                appendLine("## 复现步骤")
                appendLine(draft.reproduction.trim())
            }
            if (draft.diagnostics.isNotBlank()) {
                appendLine()
                appendLine("## 环境信息")
                appendLine(draft.diagnostics.trim())
            }
            if (draft.logExcerpt.isNotBlank()) {
                appendLine()
                appendLine("## 日志片段（已脱敏）")
                appendLine("```text")
                appendLine(draft.logExcerpt.trim())
                appendLine("```")
            }
        }
    }.trimEnd()

    fun buildUrl(issueTitle: String, body: String, label: String?): String = buildString {
        append(REPO_URL).append("/issues/new")
        append("?template=").append(TEMPLATE_FILE)
        append("&title=").append(encode(issueTitle))
        append("&body=").append(encode(body))
        if (!label.isNullOrBlank()) append("&labels=").append(encode(label))
    }

    /** 先丢日志，再逐步裁剪正文，直到链接长度可控；裁剪时避免把代理对切成半个字符。 */
    private fun fitForUrl(draft: FeedbackDraft, issueTitle: String, fullBody: String, english: Boolean = false): String {
        val label = label(draft.kind)
        if (buildUrl(issueTitle, fullBody, label).length <= MAX_URL_CHARS) return fullBody

        val withoutLog = composeBody(draft.copy(logExcerpt = ""), english)
        val notice = if (english) TRUNCATED_NOTICE_EN else TRUNCATED_NOTICE
        val withNotice = "$withoutLog\n\n$notice"
        if (buildUrl(issueTitle, withNotice, label).length <= MAX_URL_CHARS) return withNotice

        var cutLength = withoutLog.length
        while (cutLength > 200 &&
            buildUrl(issueTitle, safePrefix(withoutLog, cutLength) + "\n\n" + notice, label).length > MAX_URL_CHARS
        ) {
            cutLength = cutLength * 9 / 10
        }
        return safePrefix(withoutLog, cutLength) + "\n\n" + notice
    }

    private fun safePrefix(source: String, length: Int): String {
        var end = length.coerceIn(0, source.length)
        if (end in 1 until source.length && source[end - 1].isHighSurrogate()) end -= 1
        return source.substring(0, end)
    }

    private fun encode(value: String): String =
        URLEncoder.encode(value, "UTF-8").replace("+", "%20")

    private fun kindText(kind: FeedbackKind, english: Boolean = false): String =
        if (english) {
            when (kind) {
                FeedbackKind.SUGGESTION -> "Suggestion"
                FeedbackKind.BUG -> "Bug"
                FeedbackKind.OTHER -> "Other"
            }
        } else {
            when (kind) {
                FeedbackKind.SUGGESTION -> "建议"
                FeedbackKind.BUG -> "缺陷"
                FeedbackKind.OTHER -> "其他"
            }
        }
}
